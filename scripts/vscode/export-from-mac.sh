#!/usr/bin/env bash
# Run on the instructor's Mac. Exports the installed VS Code extensions that
# also run on Windows (checked on the VS Code Marketplace) to extensions.txt.
# Usage: scripts/vscode/export-from-mac.sh
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$HERE/extensions.txt"
CODE="$(command -v code || echo "/Applications/Visual Studio Code.app/Contents/Resources/app/bin/code")"

# Never share these (AI assistants and account-based tools). Case-insensitive regex.
EXCLUDE='^(anthropic\.|openai\.|anysphere\.|cursor|codacy-app\.|github\.copilot)'

"$CODE" --list-extensions | grep -viE "$EXCLUDE" | sort -f > "$HERE/.mac-extensions.tmp"

python3 - "$HERE/.mac-extensions.tmp" "$OUT" <<'PY'
import json, sys, urllib.request

ids = [l.strip() for l in open(sys.argv[1]) if l.strip()]
body = {
    "filters": [{"criteria": [{"filterType": 7, "value": i} for i in ids], "pageSize": 100}],
    "flags": 0x1 | 0x200,  # versions, latest only (one entry per target platform)
}
req = urllib.request.Request(
    "https://marketplace.visualstudio.com/_apis/public/gallery/extensionquery",
    data=json.dumps(body).encode(),
    headers={"Content-Type": "application/json",
             "Accept": "application/json;api-version=7.2-preview.1",
             "User-Agent": "devops-roadmap-basics/export-from-mac"})
result = json.load(urllib.request.urlopen(req, timeout=60))

platforms = {}
for ext in result["results"][0]["extensions"]:
    ext_id = f'{ext["publisher"]["publisherName"]}.{ext["extensionName"]}'.lower()
    platforms[ext_id] = {v.get("targetPlatform") or "universal" for v in ext["versions"]}

keep = []
for ext_id in ids:
    p = platforms.get(ext_id.lower())
    if p is None:
        print(f"  skip  {ext_id}  (not on the Marketplace)")
    elif p & {"universal", "win32-x64"}:
        keep.append(ext_id)
        print(f"  ok    {ext_id}")
    else:
        print(f"  skip  {ext_id}  (no Windows build: {', '.join(sorted(p))})")

with open(sys.argv[2], "w") as f:
    f.write("# VS Code extensions for the DevOps Roadmap labs (Windows-compatible).\n")
    f.write("# Generated by scripts/vscode/export-from-mac.sh. One extension ID per line.\n")
    f.write("ms-vscode-remote.remote-wsl\n")   # required on Windows to work inside Ubuntu
    for ext_id in keep:
        f.write(ext_id + "\n")
print(f"\nWrote {len(keep) + 1} extensions to {sys.argv[2]}")
PY
rm -f "$HERE/.mac-extensions.tmp"
